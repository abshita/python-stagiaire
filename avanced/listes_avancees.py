# Listes avancées

# Liste de nombres
nombres = [10, 20, 30, 40]
print("Liste initiale:", nombres)

# Ajouter un élément
nombres.append(50)
print("Après append:", nombres)

# Trier la liste
nombres.sort()
print("Après tri:", nombres)

# Extraire un sous-ensemble
sous_liste = nombres[1:4]
print("Sous-liste:", sous_liste)

# Liste de mots
mots = ["python", "java", "c++"]
print("Mots:", mots)

# On peut aussi compter des éléments
print("Nombre d'éléments:", len(mots))
