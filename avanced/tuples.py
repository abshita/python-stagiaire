# Tuples

coordonnees = (10, 20)
print("Tuple:", coordonnees)
print("Premier élément:", coordonnees[0])
print("Deuxième élément:", coordonnees[1])

# Un tuple peut contenir des données mixtes
personne = ("Alice", 25, "Paris")
print("Personne:", personne)

